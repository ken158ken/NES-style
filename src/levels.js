  const SECOND_SONG = { w1: 'green2', w2: 'castle2', w3: 'island2', w4: 'cloud2', w5: 'dedede2' };
  function roomAmbient(lv, room) {
    const nm = room.name || '';
    const water = room.map.reduce((n, r) => n + (r.split('~').length - 1), 0);
    if (/洞窟|水牢|地下|海底|寶窟/.test(nm)) return 'cave';
    if (water >= 24) return 'water';
    if (lv.theme === 'island' || lv.theme === 'cloud') return 'wind';
    if (lv.theme === 'castle' || lv.theme === 'dedede') return 'castle';
    return null;
  }
  for (const lv of KB.LEVELS) {
    lv.rooms.forEach((room, i) => {
      if (i >= 2 && !room.bossRoom && !room.secret && !room.music && SECOND_SONG[lv.id]) room.music = SECOND_SONG[lv.id];
      if (room.ambient === undefined) { const a = roomAmbient(lv, room); if (a) room.ambient = a; }
    });
  }

