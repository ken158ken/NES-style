  /* ---------------- 工具 ---------------- */
  function rows8(src, x0, y0) {           // 從 W×H 字串圖切一塊 8×8
    var out = [], y;
    for (y = 0; y < 8; y++) out.push(src[y0 + y].substr(x0, 8));
    return out;
  }
  function mapRows(rows, fn) { return rows.map(function (r) { return r.split('').map(fn).join(''); }); }
  // 16×16 字形 → 4 塊 8×8（加右下陰影：空白且左上有筆畫 → 1）
  function glyph(rows, ink, shadow) {
    var g = rows.map(function (r) { return (r + '................').substr(0, 16).split(''); });
    while (g.length < 16) g.push('................'.split(''));
    var out = [], y, x;
    for (y = 0; y < 16; y++) {
      var line = [];
      for (x = 0; x < 16; x++) {
        var on = g[y][x] !== '.';
        var sh = !on && shadow && y > 0 && x > 0 && g[y - 1][x - 1] !== '.';
        line.push(on ? ink : (sh ? shadow : '.'));
      }
      out.push(line.join(''));
    }
    return [rows8(out, 0, 0), rows8(out, 8, 0), rows8(out, 0, 8), rows8(out, 8, 8)];
  }
  function rot90(rows) {                   // 順時針旋轉 90°（車頭朝上 → 朝右）
    var n = rows.length, out = [], y, x;
    for (y = 0; y < n; y++) {
      var line = '';
      for (x = 0; x < n; x++) line += rows[n - 1 - x].charAt(y);
      out.push(line);
    }
    return out;
  }

