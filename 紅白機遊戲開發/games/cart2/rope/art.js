(function () {
  'use strict';
  var NES = window.NES = window.NES || {};
  var CT = window.CT = window.CT || {};
  var RP = CT.Rope = CT.Rope || {};
  var CHR = NES.CHR;

  var FONT = (CHR && CHR.DEMO && CHR.DEMO.FONT) || {};
  var CHARMAP = { ' ': 'SP', '-': 'DASH', '!': 'EXCL', '/': 'SLASH', '+': 'PLUS', 'x': 'MUL', ':': 'COLON',
                  '$': 'STAR', '★': 'STAR', '.': 'DOT', '=': 'EQ', '?': 'QUEST', '>': 'ARROW', '♥': 'HEART', ',': 'COMMA', '(': 'LPAREN', ')': 'RPAREN' };
  (function () {
    var i;
    for (i = 0; i <= 9; i++) CHARMAP[String(i)] = 'N' + i;
    for (i = 65; i <= 90; i++) CHARMAP[String.fromCharCode(i)] = String.fromCharCode(i);
  })();

  function E8() { return ['........', '........', '........', '........', '........', '........', '........', '........']; }
  function fill(c) { var r = '', i; for (i = 0; i < 8; i++) r += c; var o = []; for (i = 0; i < 8; i++) o.push(r); return o; }
  function mirror(rows) { return rows.map(function (r) { return r.split('').reverse().join(''); }); }
  function cut(rows, w, h) {           // rows（w*8 × h*8）→ 磚陣列（列優先）
    var out = [], tx, ty, y;
    for (ty = 0; ty < h; ty++) for (tx = 0; tx < w; tx++) {
      var t = [];
      for (y = 0; y < 8; y++) t.push(rows[ty * 8 + y].substring(tx * 8, tx * 8 + 8));
      out.push(t);
    }
    return out;
  }

  /* ============================== 背景 ============================== */
  var BG = { SP: E8(), HB: fill('1') };
  Object.keys(CHARMAP).forEach(function (ch) { var n = CHARMAP[ch]; if (FONT[n] && !BG['F_' + n]) BG['F_' + n] = FONT[n]; });
  // 狀態列字型（實心底：'.' → 色 1）
  Object.keys(CHARMAP).forEach(function (ch) { var n = CHARMAP[ch]; if (FONT[n] && !BG['H_' + n]) BG['H_' + n] = FONT[n].map(function (r) { return r.replace(/\./g, '1'); }); });
  // 地面
  BG.GR_T = ['33333333', '32323232', '22222222', '21222122', '22222222', '22212222', '22222222', '12222221'];
  BG.GR_A = ['22222222', '22122222', '22222222', '22222212', '21222222', '22222222', '22221222', '22222222'];
  BG.GR_B = ['21222222', '22222222', '22222122', '22222222', '22222222', '12222222', '22222222', '22212222'];
  BG.GR_C0 = ['22222222', '22111122', '21333312', '13222231', '13222231', '21333312', '22111122', '22222222'];   // 月面坑
  BG.BR_A = ['11111111', '22232222', '22232222', '22232222', '11111111', '22222223', '22222223', '22222223'];   // 廣場磚
  // 雲 / 丘陵
  BG.CL_L = ['........', '.....333', '...33333', '..333333', '.3333333', '33333333', '22222222', '........'];
  BG.CL_M = ['..33....', '.3333.33', '33333333', '33333333', '33333333', '33333333', '22222222', '........'];
  BG.CL_R = ['........', '333.....', '33333...', '333333..', '3333333.', '33333333', '22222222', '........'];
  BG.HL_U = ['........', '........', '........', '...1111.', '.1111111', '11111111', '11111111', '11111111'];
  BG.HL_D = ['.......1', '.....111', '...11111', '.1111111', '11111111', '11111111', '11111111', '11111111'];
  BG.HL_E = ['1.......', '111.....', '11111...', '1111111.', '11111111', '11111111', '11111111', '11111111'];
  BG.FILL1 = fill('1');
  // 星
  BG.ST1 = ['........', '........', '...3....', '........', '........', '......2.', '........', '........'];
  BG.ST2 = ['........', '.2......', '........', '....3...', '...323..', '....3...', '........', '........'];
  // 家星（月面背景，2×2）
  var PLANET = [
    '.....111111.....', '...1122222211...', '..122333222221..', '.12333332222221.', '.12333322233221.', '1223322223333221',
    '1222222233333221', '1222333223332221', '1223333322222221', '1222333222222221', '.12222222233221.', '.12222223333221.',
    '..122222233221..', '...1122222211...', '.....111111.....', '................'];
  cut(PLANET, 2, 2).forEach(function (t, i) { BG['PL_' + i] = t; });
  var MOONC = [
    '................', '......3333......', '....33333.......', '...3333.........', '..3333..........', '..333...........',
    '.3333...........', '.3333...........', '.3333...........', '.3333...........', '..333...........', '..3333..........',
    '...3333.........', '....33333.......', '......3333......', '................'];
  cut(MOONC, 2, 2).forEach(function (t, i) { BG['MO_' + i] = t; });
  // 樓群（色 1 牆、2 暗窗、3 亮窗）
  BG.BD_T = ['........', '...1....', '...1....', '11111111', '11111111', '12111211', '13111311', '11111111'];
  BG.BD_A = ['11111111', '13113111', '13113111', '11111111', '11111111', '12112111', '12112111', '11111111'];
  BG.BD_B = ['11111111', '12113111', '12113111', '11111111', '11111111', '13112111', '13112111', '11111111'];
  BG.BD_F = ['11111111', '11111111', '11111111', '11111111', '11111111', '11111111', '11111111', '11111111'];
  // 搖繩機器人（16×32；1 = 深色描邊、2 = 機身、3 = 亮面 / 眼）
  var BOT = [
    '................', '.....111111.....', '....12222221....', '...1233333321...', '...1231331321...', '...1233333321...',
    '....12222221....', '.....111111.....', '......1221......', '....11222211....', '...1222222221...', '..123322223321..',
    '..123222222321..', '..122211112221..', '..122133331221..', '..122133331221..', '..122211112221..', '..122222222221..',
    '..112222222211..', '...1111111111...', '....12211221....', '....12211221....', '....12211221....', '....12211221....',
    '...1222112221...', '..122221122221..', '..111111111111..', '................', '................', '................',
    '................', '................'];
  // 底座只到第 27 列；最下 4 列空（站在地面上：身體 rows 18..21 的底 = y 175）
  BOT = ['................', '................', '................', '................'].concat(BOT.slice(0, 28));
  // 手臂：從肩膀（第 14 列）往上接到曲柄軸心下方（x = 14..15）
  BOT = BOT.map(function (r, i) { return i < 14 ? r.substring(0, 14) + '12' : r; });
  var botL = cut(BOT, 2, 4), botR = cut(mirror(BOT), 2, 4);
  botL.forEach(function (t, i) { BG['KL_' + i] = t; });
  botR.forEach(function (t, i) { BG['KR_' + i] = t; });
  // 曲柄（16×16，中心 (8,8)，把手在半徑 5 的圓上；四影格 = 下 / 前 / 上 / 後）
  (function () {
    for (var f = 0; f < 4; f++) {
      var px = [], x, y, a = f * Math.PI / 2 + Math.PI / 2, hx = 7.5 + Math.cos(a) * 5, hy = 7.5 + Math.sin(a) * 5;
      for (y = 0; y < 16; y++) {
        px.push([]);
        for (x = 0; x < 16; x++) {
          var d = Math.sqrt((x - 7.5) * (x - 7.5) + (y - 7.5) * (y - 7.5)), v = 0;
          if (d < 3.2) v = 3; else if (d < 4.6) v = 1;
          var dh = Math.sqrt((x - hx) * (x - hx) + (y - hy) * (y - hy));
          // 曲柄桿
          var t = ((x - 7.5) * (hx - 7.5) + (y - 7.5) * (hy - 7.5)) / 25;
          if (t > 0 && t < 1) {
            var qx = 7.5 + (hx - 7.5) * t, qy = 7.5 + (hy - 7.5) * t;
            if ((x - qx) * (x - qx) + (y - qy) * (y - qy) < 1.1) v = 2;
          }
          if (dh < 2.2) v = 2; if (dh < 1.2) v = 3;
          if (y >= 11 && (x === 7 || x === 8) && v === 0) v = x === 7 ? 1 : 2;   // 軸桿往下接手臂
          px[y].push(v);
        }
      }
      var rows = px.map(function (r) { return r.map(function (v) { return '.123'.charAt(v); }).join(''); });
      cut(rows, 2, 2).forEach(function (t, i) { BG['CK' + f + '_' + i] = t; });
    }
  })();
  // 外框
  BG.FR_H = ['........', '........', '........', '33333333', '11111111', '........', '........', '........'];
  // 標題大字
  function bigLetter(ch) {
    var gl = FONT[CHARMAP[ch]], px = [], i, j, x, y, X, Y;
    for (y = 0; y < 16; y++) { px.push([]); for (x = 0; x < 16; x++) px[y].push(0); }
    for (j = 0; j < 8; j++) for (i = 0; i < 8; i++) {
      if (!gl || gl[j].charAt(i) === '.') continue;
      for (var dy = 0; dy < 2; dy++) for (var dx = 0; dx < 2; dx++) {
        X = i * 2 + dx - 1; Y = j * 2 + dy;
        if (Y + 1 < 16 && X + 1 < 16 && X + 1 >= 0 && px[Y + 1][X + 1] === 0) px[Y + 1][X + 1] = 1;
        if (X >= 0) px[Y][X] = j < 3 ? 3 : 2;
      }
    }
    return cut(px.map(function (r) { return r.map(function (v) { return '.123'.charAt(v); }).join(''); }), 2, 2);
  }
  'ROPE'.split('').forEach(function (ch) { var t = bigLetter(ch); for (var q = 0; q < 4; q++) BG['BIG_' + ch + q] = t[q]; });

  /* ============================== 精靈 ============================== */
  // 頭（16×10）
  var HEADS = {
    TICO: ['......3.........', '.....333..3.....', '..3.33333333....', '...1111111113...', '..112222222211..', '..122222222221..',
           '..122122221221..', '..122222222221..', '...1222332221...', '....11222211....'],
    BOBO: ['.......3........', '.......1........', '....11111111....', '...1222222221...', '..122222222221..', '..113333333311..',
           '..131331133131..', '..113333333311..', '...1222222221...', '....11111111....'],
    LUMI: ['...11.....11....', '..1331...1331...', '..1331...1331...', '..1331...1331...', '...1311111131...', '..112222222211..',
           '..122122221221..', '..122222222221..', '...1222332221...', '....11222211....']
  };
  // 身體 + 腿（16×14）
  var LEGS = {
    STAND: ['.....111111.....', '....13333331....', '...1233333321...', '..12.133331.21..', '..11.133331.11..', '....11333311....',
            '....12222221....', '....12211221....', '....12211221....', '....12211221....', '....12211221....',
            '...1122..2211...', '...1111..1111...', '................'],
    AIR: ['..1..111111..1..', '..2113333331122.', '...1233333321...', '....13333331....', '....13333331....', '....11333311....',
          '....12222221....', '...1222112221...', '..1221....1221..', '..1221....1221..', '..1111....1111..', '................', '................', '................'],
    TRIP: ['................', '................', '.....111111.....', '...113333331....', '..1233333333211.', '..11.13333331.21',
           '....1222222211..', '...12211112221..', '..12211...12221.', '.1221.....11111.', '.1111...........', '................', '................', '................'],
    FOOTL: ['.....111111.....', '....13333331....', '...1233333321...', '..12.133331.21..', '..11.133331.11..', '....11333311....',
            '....12222221....', '...1222112211...', '..1221..12211...', '..1111..12211...', '........12211...', '........12211...', '.......1111.....', '................'],
    FOOTR: ['.....111111.....', '....13333331....', '...1233333321...', '..12.133331.21..', '..11.133331.11..', '....11333311....',
            '....12222221....', '...1122112221...', '...11221..1221..', '...11221..1111..', '...11221........', '...11221........', '.....1111.......', '................']
  };
  function fix16(r) { r = r.replace(/ /g, '.'); while (r.length < 16) r += '.'; return r.substring(0, 16); }
  var SPR = {
    BLANK: E8(),
    BEAD: ['........', '...1....', '..131...', '.13331..', '..131...', '...1....', '........', '........'],
    BEADF: ['...1....', '..131...', '.13331..', '1333331.', '.13331..', '..131...', '...1....', '........'],
    SPARK: ['...3....', '...3....', '........', '33...33.', '........', '...3....', '...3....', '........'],
    TWINK: ['........', '........', '...3....', '..333...', '...3....', '........', '........', '........'],
    BACK: ['...33...', '..3333..', '33333333', '.333333.', '..3333..', '.333333.', '.33..33.', '........']
  };
  Object.keys(HEADS).forEach(function (who) {
    Object.keys(LEGS).forEach(function (fr) {
      var head = HEADS[who].map(fix16), legs = LEGS[fr].map(fix16), rows;
      if (fr === 'TRIP') rows = ['................', '................', '................', '................', '................', '................'].concat(head.slice(0, 10)).concat(legs.slice(2, 10));
      else rows = head.concat(legs);
      rows = rows.slice(0, 24);
      while (rows.length < 24) rows.push('................');
      cut(rows, 2, 3).forEach(function (t, i) { SPR[who + '_' + fr + '_' + i] = t; });
    });
  });

  var ART = null;
  function make() {
    if (ART) return ART;
    var bg = CHR.bank('rope_bg', BG), spr = CHR.bank('rope_spr', SPR);
    function tiles(s, pre) {
      var out = [], i, n, c;
      s = String(s); pre = pre || 'F_';
      for (i = 0; i < s.length; i++) {
        c = s.charAt(i);
        n = CHARMAP[c];
        if (n === undefined && c >= 'a' && c <= 'z') n = CHARMAP[c.toUpperCase()];
        out.push(n && BG[pre + n] ? bg.index(pre + n) : (pre === 'H_' ? bg.index('HB') : 0));
      }
      return out;
    }
    ART = {
      bg: bg, spr: spr,
      t: function (name) { return bg.index(name); },
      s: function (name) { return spr.index(name); },
      text: function (str) { return tiles(str, 'F_'); },
      hud: function (str) { return tiles(str, 'H_'); },
      big: function (ch) { return [0, 1, 2, 3].map(function (q2) { return bg.index('BIG_' + ch + q2); }); }
    };
    return ART;
  }
  RP.Art = { make: make, BG: BG, SPR: SPR, HEADS: Object.keys(HEADS), LEGS: Object.keys(LEGS) };
})();
