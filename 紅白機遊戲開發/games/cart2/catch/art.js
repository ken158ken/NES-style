/*
 * games/cart2/catch/art.js — 《星塵接球 STAR CATCH》CHR（全部原創像素；背景 bank `catch_bg`、精靈 bank `catch_spr`）
 * ---------------------------------------------------------------------------
 * 擁有者：C6-3 cart2-pop（R6）｜ 依賴：engine/chr.js（字身沿用原創 NES.CHR.DEMO.FONT）
 *
 * 主角「波羅 BOLO」：圓頂、單眼護目鏡、兩顆小輪子的拾星機器人（16×16，橘身白頂）。
 *   接星模式頭頂扛「星籃」（24×8）、頂球模式扛「托盤」（24×8）、彈跳模式改操作彈跳星球「噗噗 PUFF」（8×8，有臉）。
 * 背景（catch_bg）：
 *   F_*            字型（色 3，透明底）            FR_T / FR_B / FR_L / FR_R / FR_*  邊框（色 1 / 2）
 *   FLOOR / SOIL   地面（接星 / 頂球）             D1 / D2  星點裝飾（色 3）
 *   PL_L / PL_M / PL_R  一般平台（青）  SPRING 彈簧  SPIKE 星刺  CRUMB / CRACK 碎晶（踩過龜裂 → 消失）
 *   ICE 冰晶（滑）  GEM 星晶（收集）  GO0..GO3 星門（2×2，終點）  BLK 標題大字方塊
 * 精靈（catch_spr，全部 8×8）：
 *   BOLO_{A,B}{0..3}（2 個輪子影格 × 4 磚）、BOLO_X{0..3}（暈眩）、BASK_{L,M,R}、TRAY_{L,M,R}、
 *   STAR / GOLD / HEART / CLOCK / URCHIN（壞東西：虛空海膽）、BALL（彗星球）、PUFF0..PUFF2（噗噗：一般 / 壓扁 / 拉長）、
 *   SPARK / POOF / ARROW（風向）
 */
(function () {
  'use strict';
  var NES = window.NES = window.NES || {};
  var CT = window.CT = window.CT || {};
  var CA = CT.Catch = CT.Catch || {};
  var CHR = NES.CHR;

  var FONT = (CHR && CHR.DEMO && CHR.DEMO.FONT) || {};
  var CHARMAP = { ' ': 'SP', '-': 'DASH', '!': 'EXCL', '/': 'SLASH', '+': 'PLUS', 'x': 'MUL', ':': 'COLON', '.': 'DOT',
                  '?': 'QUEST', '=': 'EQ', '>': 'ARROW', '%': 'PCT', '(': 'LPAREN', ')': 'RPAREN', "'": 'APOS', ',': 'COMMA' };
  var i;
  for (i = 0; i <= 9; i++) CHARMAP[String(i)] = 'N' + i;
  for (i = 65; i <= 90; i++) CHARMAP[String.fromCharCode(i)] = String.fromCharCode(i);
  CHARMAP['*'] = 'STAR'; CHARMAP['#'] = 'HEART'; CHARMAP['$'] = 'COIN';

  function E8() { return ['........', '........', '........', '........', '........', '........', '........', '........']; }
  function quad(rows, w) {           // w×16 文字圖 → 8×8 磚（左上、右上、左下、右下 …）
    var out = [], tx, ty, y, cols = w / 8;
    for (ty = 0; ty < rows.length / 8; ty++) for (tx = 0; tx < cols; tx++) {
      var t = [];
      for (y = 0; y < 8; y++) t.push(rows[ty * 8 + y].substring(tx * 8, tx * 8 + 8));
      out.push(t);
    }
    return out;
  }

  /* ================= 背景 ================= */
  var BG = { SP: E8() };
  for (var k in CHARMAP) {
    if (!Object.prototype.hasOwnProperty.call(CHARMAP, k)) continue;
    var n = CHARMAP[k];
    if (FONT[n]) BG['F_' + n] = FONT[n];
  }
  // 邊框（色 1 暗、色 2 亮）：星管框
  BG.FR_T = ['........', '........', '22222222', '11111111', '12121212', '11111111', '........', '........'];
  BG.FR_B = BG.FR_T;
  BG.FR_L = ['..1211..', '..1211..', '..1211..', '..1111..', '..1211..', '..1211..', '..1211..', '..1111..'];
  BG.FR_R = BG.FR_L;
  BG.FR_C = ['........', '........', '..2222..', '..2112..', '..2112..', '..2222..', '........', '........'];
  // 地面：上緣亮線 + 晶砂
  BG.FLOOR = ['33333333', '22222222', '21222212', '22122222', '22222122', '12222222', '22221222', '22222222'];
  BG.SOIL = ['22122222', '22222212', '12222222', '22222122', '22212222', '22222222', '21222221', '22222222'];
  BG.D1 = ['........', '........', '........', '...3....', '........', '........', '........', '........'];
  BG.D2 = ['........', '...3....', '..333...', '...3....', '........', '........', '........', '........'];
  BG.D3 = ['........', '......2.', '........', '........', '........', '.2......', '........', '........'];
  // 平台（色 2 青身 + 色 3 亮緣 + 色 1 暗底）
  BG.PL_L = ['.3333333', '32222222', '32212222', '12222122', '.1111111', '........', '........', '........'];
  BG.PL_M = ['33333333', '22222222', '22122221', '22222222', '11111111', '........', '........', '........'];
  BG.PL_R = ['3333333.', '22222223', '22212223', '22122221', '1111111.', '........', '........', '........'];
  BG.SPRING = ['33333333', '13111131', '..1..1..', '.1.11.1.', '..1..1..', '.1.11.1.', '11111111', '........'];
  BG.SPIKE = ['........', '...3...3', '..31..31', '..31..31', '.3111311', '.3111311', '11111111', '11111111'];
  BG.CRUMB = ['33333333', '23222322', '22232222', '32222232', '12121212', '.1.1.1.1', '........', '........'];
  BG.CRACK = ['33.333.3', '2.2.2.22', '.2.1.2..', '3..2..3.', '.1...1.2', '1.....1.', '........', '........'];
  BG.ICE = ['33333333', '33232333', '32323232', '22222222', '11111111', '........', '........', '........'];
  BG.GEM = ['........', '...3....', '..323...', '.32223..', '..121...', '...1....', '........', '........'];
  // 星門 16×16（色 1/2/3 的旋渦）
  var GO = [
    '.....111111.....',
    '...1122222211...',
    '..122333333221..',
    '.12233222233221.',
    '.12332111123321.',
    '1233211..1123321',
    '123211.33.112321',
    '12321.3333.12321',
    '12321.3333.12321',
    '123211.33.112321',
    '1233211..1123321',
    '.12332111123321.',
    '.12233222233221.',
    '..122333333221..',
    '...1122222211...',
    '.....111111.....'
  ];
  var gq = quad(GO, 16);
  for (i = 0; i < 4; i++) BG['GO' + i] = gq[i];
  BG.BLK = ['.333333.', '33333332', '33333332', '33333332', '33333332', '33333332', '33333332', '.222222.'];
  BG.BLKS = ['........', '.111111.', '.111111.', '.111111.', '.111111.', '.111111.', '.111111.', '........'];

  /* ================= 精靈 ================= */
  // 波羅：1 = 深色描邊、2 = 橘身、3 = 白頂 / 護目鏡
  var BOLO = [
    '................',
    '....11111111....',
    '...1333333331...',
    '..133333333331..',
    '..133111111331..',
    '..131322223131..',
    '..131233332131..',
    '..133111111331..',
    '..122222222221..',
    '..121222222121..',
    '.1221222222122l.',
    '.12.12222221.21.',
    '.1..11111111..1.',
    '...111....111...',
    '..1W1W1..1W1W1..',
    '...111....111...'
  ];
  function boloRows(frame, dizzy) {
    return BOLO.map(function (r, y) {
      r = r.replace(/l/g, '1');
      if (y === 14) r = frame ? r.replace(/W/g, '3') : r.replace(/W/g, '.');
      if (y === 13 || y === 15) r = frame ? r.replace(/111/g, '1.1') : r;
      if (dizzy && (y === 5 || y === 6)) r = y === 5 ? '..131.3..3.131..' : '..131..33..131..';
      return r.replace(/W/g, '.');
    });
  }
  var SPR = { BLANK: E8() };
  var fr;
  [['A', 0, false], ['B', 1, false], ['X', 0, true]].forEach(function (d) {
    fr = quad(boloRows(d[1], d[2]), 16);
    for (var q = 0; q < 4; q++) SPR['BOLO_' + d[0] + q] = fr[q];
  });
  // 星籃 24×8（網狀）
  var BASK = [
    '1......................1',
    '13....................31',
    '133333333333333333333331',
    '.12121212121212121212121',
    '.21212121212121212121212',
    '..1212121212121212121212',
    '...11111111111111111111.',
    '..........1111..........'
  ];
  var TRAY = [
    '........................',
    '3......................3',
    '333333333333333333333333',
    '122222222222222222222221',
    '.1111111111111111111111.',
    '..........1..1..........',
    '..........1..1..........',
    '..........1111..........'
  ];
  ['L', 'M', 'R'].forEach(function (s, j) {
    SPR['BASK_' + s] = BASK.map(function (r) { return r.substring(j * 8, j * 8 + 8); });
    SPR['TRAY_' + s] = TRAY.map(function (r) { return r.substring(j * 8, j * 8 + 8); });
  });
  SPR.STAR = ['...3....', '..333...', '3333333.', '.33233..', '..323...', '.33.33..', '.3...3..', '........'];
  SPR.GOLD = ['...1....', '..131...', '.13331..', '1332331.', '.13331..', '..131...', '...1....', '........'];
  SPR.HEART = ['........', '.11.11..', '1331331.', '1333331.', '.13331..', '..131...', '...1....', '........'];
  SPR.CLOCK = ['..111...', '.13331..', '1333131.', '1331331.', '1333331.', '.13331..', '..111...', '........'];
  SPR.URCHIN = ['1..1..1.', '.1.1.1..', '..222...', '11232211', '..222...', '.1.1.1..', '1..1..1.', '........'];
  SPR.BALL = ['..1111..', '.133321.', '13332221', '13322221', '12222221', '12222211', '.122211.', '..1111..'];
  SPR.PUFF0 = ['..1111..', '.122221.', '12322321', '12122121', '12222221', '12211221', '.122221.', '..1111..'];
  SPR.PUFF1 = ['........', '........', '.111111.', '12322321', '12122121', '12211221', '12222221', '.111111.'];
  SPR.PUFF2 = ['..1111..', '.122221.', '.132231.', '.121121.', '.122221.', '.121121.', '.122221.', '..1111..'];
  SPR.SPARK = ['...3....', '...3....', '........', '33.3.33.', '........', '...3....', '...3....', '........'];
  SPR.POOF = ['3..3..3.', '.3...3..', '..3.3...', '33...33.', '..3.3...', '.3...3..', '3..3..3.', '........'];
  SPR.ARROW = ['........', '....3...', '....33..', '3333333.', '....33..', '....3...', '........', '........'];
  SPR.SOLID = ['.333333.', '33333333', '33333333', '33333333', '33333333', '33333333', '33333333', '.333333.'];

  var ART = null;
  function make() {
    if (ART) return ART;
    var bg = CHR.bank('catch_bg', BG), spr = CHR.bank('catch_spr', SPR);
    function text(s) {
      var out = [], j, nm;
      s = String(s);
      for (j = 0; j < s.length; j++) {
        nm = CHARMAP[s.charAt(j)];
        if (nm === undefined) nm = CHARMAP[s.charAt(j).toUpperCase()];
        out.push(nm && BG['F_' + nm] ? bg.index('F_' + nm) : 0);
      }
      return out;
    }
    ART = {
      bg: bg, spr: spr,
      t: function (name) { return bg.index(name); },
      s: function (name) { return spr.index(name); },
      text: text
    };
    return ART;
  }
  CA.Art = { make: make, BG: BG, SPR: SPR, CHARMAP: CHARMAP };
})();
