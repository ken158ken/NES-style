  var ART = null;
  function make() {
    if (ART) return ART;
    var bg = CHR.bank('slash_bg', BG), spr = CHR.bank('slash_spr', SPR);
    ART = {
      bg: bg, spr: spr,
      t: function (name) { return bg.index(name); },
      s: function (name) { return spr.index(name); },
      q: function (name) { return [0, 1, 2, 3].map(function (k) { return spr.index(name + '_' + k); }); },
      text: function (s) {
        var out = [], i, n, c;
        s = String(s);
        for (i = 0; i < s.length; i++) {
          c = s.charAt(i);
          n = CHARMAP[c] || CHARMAP[c.toUpperCase()];
          out.push(n && BG['F_' + n] ? bg.index('F_' + n) : 0);
        }
        return out;
      },
      hud: function (s) {
        var out = [], i, n, c;
        s = String(s);
        for (i = 0; i < s.length; i++) {
          c = s.charAt(i);
          n = CHARMAP[c] || CHARMAP[c.toUpperCase()];
          out.push(n && BG['H_' + n] ? bg.index('H_' + n) : bg.index('SOLID1'));
        }
        return out;
      },
      big: function (ch) { return [0, 1, 2, 3].map(function (q2) { return bg.index('BIG_' + ch + q2); }); }
    };
    return ART;
  }
  SL.Art = { make: make, BG: BG, SPR: SPR };
