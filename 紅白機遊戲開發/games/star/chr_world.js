  function dots(n) { return n > 0 ? new Array(n + 1).join('.') : ''; }

  // W(width, rows)：把「自然寬度」的手繪列補成固定寬度，避免逐列數字元。
  //   'xxxx'        → 靠左，右側補 '.'
  //   [left, 'xx']  → 左邊先補 left 個 '.'，右側再補滿
  //   null          → 整列空白
  function W(width, rows, height) {
    var out = [], i, s, h = height || width;      // 預設高 = 寬（8×8 / 16×16 / 32×32）
    if (rows.length > h) throw new Error('chr_world: 列數 ' + rows.length + ' > ' + h);
    for (i = 0; i < h; i++) {
      s = (i < rows.length) ? rows[i] : '';
      if (s === null || s === undefined) s = '';
      else if (typeof s !== 'string') s = dots(s[0]) + s[1];
      if (s.length > width) throw new Error('chr_world: 第 ' + i + ' 列超過 ' + width + ' 字元（' + s.length + '）');
      out.push(s + dots(width - s.length));
    }
    return out;
  }
  function mir(rows) {                       // 水平鏡像（給 _R 版本用）
    var out = [], i;
    for (i = 0; i < rows.length; i++) out.push(rows[i].split('').reverse().join(''));
    return out;
  }
