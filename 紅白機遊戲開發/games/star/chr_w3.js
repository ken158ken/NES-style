  function dots(n) { return n > 0 ? new Array(n + 1).join('.') : ''; }
  function W(width, rows, height) {
    var out = [], i, s, h = height || width;
    if (rows.length > h) throw new Error('chr_w3: 列數 ' + rows.length + ' > ' + h);
    for (i = 0; i < h; i++) {
      s = (i < rows.length) ? rows[i] : '';
      if (s === null || s === undefined) s = '';
      if (s.length > width) throw new Error('chr_w3: 第 ' + i + ' 列超過 ' + width + ' 字元（' + s.length + '）');
      out.push(s + dots(width - s.length));
    }
    return out;
  }
