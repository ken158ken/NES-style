#!/usr/bin/env python3
"""tools/cjk_glyphs.py — 卡帶五中文文字系統的離線字形工具（R9 C9-0 cart5-text）

把 games/cart5 各遊戲文字裡「實際用到的」全形字，用 Noto Sans CJK TC（SIL OFL）點陣化成
16×16 位元圖，連同原創 8×8 半形字型一起寫進 games/cart5/glyphs.js（`CT.GLYPHS`）。
執行期 games/cart5/text.js（`CT.Text`）把當頁需要的字形動態寫進圖樣表保留區（計 VBlank 預算）。

用法（PY = ../卡比之星/.venv/bin/python）：
    $PY tools/cjk_glyphs.py              # 掃描 → 重產 games/cart5/glyphs.js
    $PY tools/cjk_glyphs.py --check      # 只檢查：有字沒收 / 字形與 Noto 不一致 / 多收 → exit 1（run_all 用）
    $PY tools/cjk_glyphs.py --list       # 列出每個檔用到幾個字、哪些字是新的
    $PY tools/cjk_glyphs.py --render 星  # 印出單字點陣（除錯）

掃描約定（docs/ENGINE_API.md「卡帶五文字系統」）：
  1. games/cart5/**/*.js（glyphs.js 與選單設定 cart.js 除外）裡**字串常值**（'…' "…" `…`）的非 ASCII 字；註解不算。
  2. games/cart5/**/text*.txt、text*.json 的全部非 ASCII 字（純資料檔，可選）。
  3. ALWAYS：系統自己用的符號（▼ ▶ 全形空白 … 等）。
  換行 / 控制字元不收；ASCII（0x20~0x7E）一律用 8×8 半形字型，不另收。

點陣規格（測試 games/cart5/test_text.py 逐位元比對 render()）：
  NotoSansCJK-Regular.ttc index 3（TC），15px，於 (0,0) 繪製、取 L 通道 ≥ 90 為 1；
  取第 5~20 列（共 16 列）；字身高出第 5 列就整字上移、低於第 20 列就上移到剛好收進（不裁切）；
  寬度 16 欄（15px 字身右側自然留 1 欄字距）。
"""
