def js_strings(src):
    """極簡 JS 掃描：回傳所有字串常值（含模板字串）的內容；略過 // 與 /* */ 註解、正規式常值。"""
    out = []
    i, n = 0, len(src)
    prev = ''          # 前一個有意義字元（判斷 / 是除號還是正規式）
    while i < n:
        c = src[i]
        if c == '/' and i + 1 < n and src[i + 1] == '/':
            j = src.find('\n', i)
            i = n if j < 0 else j
            continue
        if c == '/' and i + 1 < n and src[i + 1] == '*':
            j = src.find('*/', i + 2)
            i = n if j < 0 else j + 2
            continue
        if c in '\'"`':
            q = c
            j = i + 1
            buf = []
            while j < n and src[j] != q:
                if src[j] == '\\' and j + 1 < n:
                    buf.append(src[j:j + 2])
                    j += 2
                    continue
                if q != '`' and src[j] == '\n':
                    break
                buf.append(src[j])
                j += 1
            out.append(''.join(buf))
            i = j + 1
            prev = 'a'
            continue
        if c == '/' and (prev == '' or prev in '(,=:[!&|?{};+-*%<>~^'):
            # 正規式常值：跳到結尾的 /（處理跳脫與字元類）
            j = i + 1
            cls = False
            while j < n and src[j] != '\n':
                if src[j] == '\\':
                    j += 2
                    continue
                if src[j] == '[':
                    cls = True
                elif src[j] == ']':
                    cls = False
                elif src[j] == '/' and not cls:
                    break
                j += 1
            i = j + 1
            prev = 'a'
            continue
        if not c.isspace():
            prev = c
        i += 1
    return out


def wanted_chars(s):
    """字串中需要 16×16 字形的字：非 ASCII、非控制字元（\\u 跳脫也解開）"""
    def unesc(m):
        return chr(int(m.group(1) or m.group(2), 16))
    s = re.sub(r'\\u\{([0-9a-fA-F]+)\}|\\u([0-9a-fA-F]{4})', unesc, s)
    return [ch for ch in s if ord(ch) > 0x7E and ch not in '\u00a0\u200b\ufeff' and not (0xD800 <= ord(ch) <= 0xDFFF)]


def scan():
    """→ (有序字集, {相對路徑: 字集})"""
    per = {}
    for base, dirs, files in os.walk(CART):
        dirs.sort()
        for fn in sorted(files):
            p = os.path.join(base, fn)
            rel = os.path.relpath(p, ROOT)
            if p == OUT or p == os.path.join(CART, 'cart.js'):   # cart.js = 選單點陣（shell 用，不經 CT.Text）
                continue
            if fn.endswith('.js'):
                with open(p, encoding='utf-8') as f:
                    src = f.read()
                cs = []
                for s in js_strings(src):
                    cs.extend(wanted_chars(s))
            elif fn.startswith('text') and (fn.endswith('.txt') or fn.endswith('.json')):
                with open(p, encoding='utf-8') as f:
                    cs = wanted_chars(f.read())
            else:
                continue
            if cs:
                per[rel] = set(cs)
    allc = set(ALWAYS)
    for v in per.values():
        allc |= v
    return sorted(allc), per


def load_existing():
    """讀現有 glyphs.js 的 cjk 表（給 --check / --list）"""
    if not os.path.exists(OUT):
        return {}, {}
    with open(OUT, encoding='utf-8') as f:
        src = f.read()
    m = re.search(r'/\*JSON\*/(.*?)/\*END\*/', src, re.S)
    if not m:
        return {}, {}
    d = json.loads(m.group(1))
    return d.get('cjk', {}), d.get('ascii', {})


def write(chars):
    cjk = {ch: glyph_hex(ch) for ch in chars}
    asc = {ch: ascii_hex(ch) for ch in sorted(ASCII_ART)}
    payload = {'v': 1, 'spec': SPEC, 'count': len(cjk), 'ascii': asc, 'cjk': cjk}
    body = json.dumps(payload, ensure_ascii=False, separators=(',', ':'))
    # 每字一行（diff 友善）
    body = body.replace('","', '",\n"')
    src = ('/*\n'
           ' * games/cart5/glyphs.js — 卡帶五文字系統的字形資料（CT.GLYPHS）。**自動產生，不要手改**：\n'
           ' *   $PY tools/cjk_glyphs.py        （掃描 games/cart5 各遊戲文字後重產；--check 驗證）\n'
           ' * 全形字：Noto Sans CJK TC（SIL Open Font License 1.1，© Google / Adobe）點陣化，規格 ' + SPEC + '；\n'
           ' *   每字 64 位十六進位 = 16 列 × 16 位元（左 = 高位元）。\n'
           ' * 半形字：原創 8×8（0x20~0x7E），每字 16 位十六進位 = 8 列 × 8 位元。\n'
           ' * 共 %d 個全形字。\n'
           ' */\n'
           '(function () {\n'
           "  'use strict';\n"
           '  var CT = window.CT = window.CT || {};\n'
           '  CT.GLYPHS = /*JSON*/' % len(cjk) + body + '/*END*/;\n'
           '})();\n')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(src)
    return len(cjk)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='只檢查不寫檔；不一致 → exit 1')
    ap.add_argument('--list', action='store_true', help='列出各檔用字')
    ap.add_argument('--render', help='印出單字點陣')
    a = ap.parse_args()
    if a.render:
        for ch in a.render:
            print(ch, glyph_hex(ch))
            for r in render(ch):
                print('  ' + format(r, '016b').replace('0', '.').replace('1', '#'))
        return 0
    chars, per = scan()
    if a.list:
        old, _ = load_existing()
        for rel in sorted(per):
            new = sorted(c for c in per[rel] if c not in old)
            print('%-48s %4d 字%s' % (rel, len(per[rel]), ('  新：' + ''.join(new)) if new else ''))
        print('合計 %d 字（現有 glyphs.js %d 字）' % (len(chars), len(old)))
        return 0
    if a.check:
        old, oasc = load_existing()
        missing = [c for c in chars if c not in old]
        extra = [c for c in old if c not in set(chars)]
        bad = [c for c in chars if c in old and old[c] != glyph_hex(c)]
        abad = [c for c in ASCII_ART if oasc.get(c) != ascii_hex(c)]
        ok = not (missing or extra or bad or abad)
        print('cjk_glyphs --check: %d 字、缺 %d、多 %d、點陣不符 %d、半形不符 %d → %s'
              % (len(chars), len(missing), len(extra), len(bad), len(abad), 'OK' if ok else '請重跑 tools/cjk_glyphs.py'))
        if missing:
            print('  缺：' + ''.join(missing[:80]))
        if extra:
            print('  多：' + ''.join(extra[:80]))
        return 0 if ok else 1
    n = write(chars)
    print('寫入 %s：全形 %d 字、半形 %d 字（%s）' % (os.path.relpath(OUT, ROOT), n, len(ASCII_ART), SPEC))
    return 0


