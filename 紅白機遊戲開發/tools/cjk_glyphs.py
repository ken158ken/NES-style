def ascii_hex(ch):
    """8×8 半形字 → 16 位十六進位（每列 1 byte，左 = 高位元）"""
    rows = ASCII_ART[ch]
    assert len(rows) == 8 and all(len(r) == 8 for r in rows), ch
    return ''.join('%02x' % int(r.replace('.', '0').replace('#', '1'), 2) for r in rows)


