_font = None


def font():
    global _font
    if _font is None:
        from PIL import ImageFont
        _font = ImageFont.truetype(FONT_PATH, FONT_SIZE, index=FONT_INDEX)
    return _font


def render(ch):
    """單一全形字 → 16 個 16 位元整數（第 0 列在前，左 = 高位元）。規格見檔頭。"""
    from PIL import Image, ImageDraw
    H = 32
    im = Image.new('L', (20, H), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=font(), fill=255)
    px = im.load()
    ink = [[1 if px[x, y] >= THRESHOLD else 0 for x in range(20)] for y in range(H)]
    ys = [y for y in range(H) if any(ink[y])]
    xs = [x for x in range(20) if any(ink[y][x] for y in range(H))]
    top = TOP
    left = 0
    if ys:
        if ys[0] < top:
            top = ys[0]
        if ys[-1] > top + 15:
            top = ys[-1] - 15
        if xs[-1] > 15:
            left = xs[-1] - 15
    rows = []
    for y in range(top, top + 16):
        v = 0
        for x in range(16):
            if 0 <= y < H and ink[y][x + left]:
                v |= 1 << (15 - x)
        rows.append(v)
    return rows


def glyph_hex(ch):
    return ''.join('%04x' % r for r in render(ch))


